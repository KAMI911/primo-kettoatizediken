def asm(s):
    out, run = [], ""
    for ch in s:
        if ch in ACC:
            if run: out.append('"%s"' % run); run = ""
            out.append("0x%02X" % (0x80 + ACC.index(ch)))
        else:
            assert 32 <= ord(ch) < 96, "unsupported character %r" % ch
            run += ch
    if run: out.append('"%s"' % run)
    return ", ".join(out + ["0"])

def write(path, d):
    L = ["; generated by tools/gen_text.py - do not edit"]
    for k in ("name1", "name2", "title", "score", "best", "snd_on", "snd_off", "tag", "start", "k_help", "k_snd", "k_mode", "k_quit",
              "on", "off", "colour", "mono", "credit"):
        L.append("txt_%s: defb %s" % (k, asm(d[k])))
    for k in ("msg_help", "msg_win", "msg_over"):
        L.append("%s: defb %s" % (k, asm(d[k])))
    L.append("help_tbl:")
    for line in d["help"]:
        assert len(line) <= 30, line
        L.append("        defb %s" % asm(line))
    L.append("        defb 0")
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")

def font_ext(font_inc, path):
    rows = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", open(font_inc).read())]
    glyph = lambda c: rows[(ord(c) - 32) * 8:(ord(c) - 32) * 8 + 8]
    L = ["; accented capitals (codes 0x80..0x88: %s), generated by tools/gen_text.py from the base font" % ACC, "font_ext:"]
    for i, b in enumerate(BASE):
        g = glyph(b); assert g[0] == 0
        g[0] = MARK[i]
        L.append("        defb " + ",".join("0x%02X" % x for x in g))
    open(path, "w").write("\n".join(L) + "\n")

